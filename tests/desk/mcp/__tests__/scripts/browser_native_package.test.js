test("in-memory signing requires a fresh persisted attempt before the irreversible external operation", async () => {
  const p = await api()
  const events = []
  let calls = 0
  const input = Buffer.from("synthetic signing input")
  const signer = async (digest, bytes) => {
    calls++
    assert.deepEqual(bytes, input)
    assert.equal(digest.toString("hex"), hash(input))
    assert.deepEqual(events, ["reserved", "sign-issued"])
    throw new Error("external result unknown")
  }
  await assert.rejects(() => p.issueSignature(input, signer, {
    reserve: () => events.push("reserved"), record: state => events.push(state),
  }), /external result unknown/u)
  assert.equal(calls, 1)
  assert.deepEqual(events, ["reserved", "sign-issued"], "never claim a signature returned after failure")
  await assert.rejects(() => p.issueSignature(input, signer, {
    reserve: () => { throw new Error("already reserved") }, record: () => {},
  }), /already reserved/u)
  assert.equal(calls, 1, "a failed reservation cannot issue another signature")
  const completed = []
  const signature = await p.issueSignature(input, async () => Buffer.from("external result"), {
    reserve: () => completed.push("reserved"), record: state => completed.push(state),
  })
  assert.equal(signature.toString(), "external result")
  assert.deepEqual(completed, ["reserved", "sign-issued", "signature-returned"])
})

