function fixture(t) {
  const scratch = realpathSync(mkdtempSync(path.join(os.tmpdir(), "browser-package-")))
  t.after(() => rmSync(scratch, { recursive: true, force: true }))
  const repo = path.join(scratch, "repo")
  mkdirSync(repo)
  const put = (file, bytes) => {
    const target = path.join(repo, file)
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, bytes)
  }
  // Fixture-only, in-memory keys: no publisher key, receipt or Azure operation.
  const { privateKey, publicKey } = generateKeyPairSync("rsa", { modulusLength: 2048 })
  const spki = publicKey.export({ type: "spki", format: "der" })
  const extensionId = hash(spki).slice(0, 32).replace(/[0-9a-f]/gu, digit => String.fromCharCode(97 + parseInt(digit, 16)))
  const publisher = { extensionId, spkiSha256: hash(spki) }
  for (const name of names) put(`plugins/desk/browser-extension/${name}`,
    readFileSync(path.join(repository, "plugins/desk/browser-extension", name)))
  const manifestFile = "plugins/desk/browser-extension/manifest.json"
  const manifest = JSON.parse(readFileSync(path.join(repo, manifestFile)))
  Object.assign(manifest, { key: spki.toString("base64"), version: "1.1.1", update_url: feed })
  put(manifestFile, JSON.stringify(manifest, null, 2) + "\n")
  const extensionRoot = path.join(repo, "plugins/desk/browser-extension")
  const extensionSourceDigest = computeSourceDigest(extensionRoot)
  put("plugins/desk/browser-extension/source-digest.mjs",
    `// Generated by build.mjs; no profile or relay credentials.\nexport const SOURCE_DIGEST = "${extensionSourceDigest}";\n`)
  const extension = new Map(names.map(name => [name, readFileSync(path.join(extensionRoot, name))]))
  const sources = new Map([["mcp/package.json", Buffer.from('{"name":"@ourostack/desk-mcp","type":"module","version":"1.4.0-alpha.6"}\n')]])
  const artifactManifest = Buffer.from('{"fixture":"native asset manifest"}\n')
  for (const [name, bytes] of sources) put(`plugins/desk/${name}`, bytes)
  put("plugins/desk/mcp/artifacts/browser-messaging/manifest.json", artifactManifest)
  for (const file of [...release.DESK_VERSION_FILES, release.CHANGELOG]) put(file, readFileSync(path.join(repository, file)))
  put("plugins/desk/changelog.d/README.md", "fixture fragment rules\n")
  const deskVersion = JSON.parse(readFileSync(path.join(repo, "plugins/desk/.claude-plugin/plugin.json"))).version
  if (deskVersion !== "3.2.0-alpha.333") release.replaceVersion(repo, release.DESK_VERSION_FILES, deskVersion, "3.2.0-alpha.333")
  // These fixtures attest exact input bytes, including any host line endings.
  // Do not let an inherited core.autocrlf setting rewrite their Git oracle.
  put(".gitattributes", "* -text\n")
  const distributionDigest = inventoryDigest(new Map([...sources,
    ...[...extension].map(([name, bytes]) => [`extension/${name}`, bytes]),
    ["artifact-manifest.json", artifactManifest]]))
  const distribution = { extension, sources, artifactManifest, extensionId, extensionSourceDigest, distributionDigest }
  const git = (...args) => {
    const result = spawnSync("git", ["-c", "user.name=fixture", "-c", "user.email=fixture@example.invalid", ...args],
      { cwd: repo, encoding: "utf8" })
    assert.equal(result.status, 0, result.stderr)
    return result.stdout.trim()
  }
  git("init", "-q", "-b", "main")
  git("add", ".")
  git("commit", "-qm", "packaging source")
  let signatures = 0
  return { repo, put, git, publisher, distribution, privateKey, publicKey, scratch,
    output: path.join(scratch, "packet"),
    sourceCommit: git("rev-parse", "HEAD"),
    signDigest: (digest, input) => {
      signatures++
      assert.equal(hash(input), digest.toString("hex"))
      return sign("sha256", input, privateKey)
    },
    signatures: () => signatures }
}

test("normal package verifies real CRX3 crypto and all eleven files across an honest Desk-only version fold", async t => {
  const p = await api()
  const f = fixture(t)
  const produced = await p.createPackage(f)
  assert.equal(produced.status, "signed-package-not-installed-proof")
  assert.equal(f.signatures(), 1)
  const folded = release.releaseDesk({ root: f.repo, date: "2026-10-21", stage: "rc" })
  assert.match(folded.to, /-rc\.1$/u)
  f.git("add", ".")
  f.git("commit", "-qm", "normal Desk version fold")
  const checked = await p.verifyPackage({ ...f, artifacts: f.output })
  assert.equal(checked.sourceCommit, f.sourceCommit, "never relabel the packaging source as the later release SHA")
  assert.notEqual(checked.sourceCommit, f.git("rev-parse", "HEAD"))
  assert.equal(checked.normalDistributionDigest, f.distribution.distributionDigest)
  assert.equal(checked.verification.localSignature, true)
  assert.equal(checked.verification.browserInstall, "UNPROVED")
  assert.equal(checked.archiveInventory.length, 11)
  assert.ok(!JSON.stringify(checked).includes(f.scratch))
  const provenanceFile = path.join(f.output, "provenance.json")
  const original = readFileSync(provenanceFile)
  writeFileSync(provenanceFile, JSON.stringify({ ...checked, sourceCommit: f.git("rev-parse", "HEAD") }))
  await assert.rejects(() => p.verifyPackage({ ...f, artifacts: f.output }),
    "even a byte-equivalent version-fold commit cannot replace the signed packaging source SHA")
  writeFileSync(provenanceFile, original)
})

