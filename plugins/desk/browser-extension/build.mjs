// Offline artifact verification only; never imported by the service worker.
// The native-bootstrap consumer must recompute these bytes independently before
// comparing a fresh protocolVersion:1 ready.sourceDigest.
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

export const SOURCE_FILES = Object.freeze([
  "background.mjs", "context-engine.mjs", "manifest.json",
  "token.html", "token.mjs", "vendor/maintained.mjs",
])

export function computeSourceDigest(directory = new URL("./", import.meta.url)) {
  const base = directory instanceof URL ? directory : pathToFileURL(resolve(directory) + "/")
  const hash = createHash("sha256")
  for (const name of SOURCE_FILES) {
    const bytes = readFileSync(new URL(name, base))
    hash.update(name + "\0" + bytes.length + "\0")
    hash.update(bytes)
  }
  return hash.digest("hex")
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = `// Generated by build.mjs; no profile or relay credentials.\nexport const SOURCE_DIGEST = "${computeSourceDigest()}";\n`
  const output = new URL("./source-digest.mjs", import.meta.url)
  if (process.argv[2] === "--write") writeFileSync(output, text)
  else if (process.argv[2] === "--check") {
    if (readFileSync(output, "utf8") !== text) throw new Error("extension_source_digest_drift")
  } else throw new Error("Use --write or --check")
}
