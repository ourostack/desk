import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const HASH = {
  full: "e77f9014417f5107332b80b8f5d4cfce2d83a7e269a85b0aa771576e045737ac",
  relay: "cc75f9fab056fcae9d2e903613d09f06cbcefe15a8c64a7417a1ee273f203d16",
  group: "855086fd8c67e144134de41a9e8fdb5b91b657f884a9ebf9b3c42a5f059549ab",
}
const digest = text => createHash("sha256").update(text).digest("hex")
function replaceOnce(source, before, after) {
  if (source.split(before).length !== 2) throw new Error("unsupported_vendor_transform")
  return source.replace(before, after)
}
function omit(source, start, end) {
  const a = source.indexOf(start), b = source.indexOf(end, a + start.length)
  if (a < 0 || b < 0) throw new Error("unsupported_vendor_transform")
  return source.slice(0, a) + source.slice(b)
}

// Only the audited official 0.4 compiled input is accepted. Region hashes are
// independent, so neither marker drift nor a partial textual match is enough.
export function extract(source) {
  if (typeof source !== "string" || digest(source) !== HASH.full) throw new Error("unsupported_vendor_source")
  let relay = source.slice(0, source.indexOf("//#region src/pendingConnection.ts"))
  let group = source.slice(source.indexOf("//#region src/connectedTabGroup.ts"), source.indexOf("//#region src/background.ts"))
  if (digest(relay) !== HASH.relay || digest(group) !== HASH.group) throw new Error("unsupported_vendor_source")
  relay = replaceOnce(relay, 'console.log("[Extension]", ...args);', "/* No command, URL, exception or credential diagnostics. */")
  relay = replaceOnce(relay, 'this._sendError(-32700, `Error parsing message: ${error.message}`);',
    'this._sendError(-32700, "native_relay_message_invalid");')
  relay = replaceOnce(relay, "response.error = error.message;", 'response.error = error.code ?? "native_relay_failed";')
  relay = replaceOnce(relay, "\t\tconst response = { id: message.id };",
    '\t\tif (!message || Array.isArray(message) || typeof message !== "object" ||\n' +
    '\t\t\t!["string", "number"].includes(typeof message.id) || typeof message.method !== "string" ||\n' +
    '\t\t\t(message.params !== undefined && !Array.isArray(message.params))) {\n' +
    '\t\t\tthis._sendError(-32600, "native_relay_message_invalid");\n\t\t\treturn;\n\t\t}\n' +
    "\t\tconst response = { id: message.id };")
  // No detached candidate/grace period is authority. Retain pages on disconnect.
  relay = omit(relay, "\t_maybeScheduleReattach(tabId) {", "\t_tabIdForEventArgs(")
  relay = replaceOnce(relay, '\t\t\tconst reason = args[1];\n', "")
  relay = replaceOnce(relay, '\t\t\tif (reason === "target_closed" && this._maybeScheduleReattach(tabId)) return;\n', "")
  // Awaited initialization is a Desk change: grouping and readback must finish
  // before the stock Chrome-API protocol announces its first tab and readiness.
  group = omit(group, "async function cleanupStalePlaywrightGroups()", "var ConnectedTabGroup = class")
  group = replaceOnce(group,
    "\t\tthis._connection.attachTab(selectedTab);\n\t\tthis._connection.didInitialize();",
    "\t}\n\tasync initialize(selectedTab) {\n\t\tawait this._addTabToGroup(selectedTab.id);\n\t\tthis._connection.attachTab(await chrome.tabs.get(selectedTab.id));\n\t\tthis._connection.didInitialize();")
  group = replaceOnce(group, "\t\t\t\tungroupTabs([tabId]);\n", "")
  group = replaceOnce(group,
    "\t\tthis._addTabToGroup(tabId);",
    "\t\tthis._addTabToGroup(tabId).catch(() => this.onfailure?.());")
  group = replaceOnce(group,
    "\t\tconst groupTabs = [...this._groupTabIds];\n\t\tthis._groupTabIds.clear();\n\t\tif (groupTabs.length) ungroupTabs(groupTabs);\n", "")
  group = replaceOnce(group, '\t\t\tdebugLog("Error adding tab to group:", error);', "\t\t\tthrow error;")
  group = omit(group, "async function ungroupTabs(tabIds)", "async function retryOnDrag(fn)")
  return "// Generated by tools/browser-extension/extract.mjs; do not edit.\n" +
    "// Microsoft Playwright extension 0.4; Apache-2.0. See PROVENANCE.md.\n" +
    "export function maintainedComponents(chrome, WebSocket) {\n" + relay + group +
    "\nreturn { RelayConnection, ConnectedTabGroup, uniqueGroupStyle };\n}\n"
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = readFileSync(new URL("./upstream/background-0.4.mjs.txt", import.meta.url), "utf8")
  const generated = extract(source)
  const output = new URL("../../plugins/desk/browser-extension/vendor/maintained.mjs", import.meta.url)
  if (process.argv[2] === "--check") {
    if (readFileSync(output, "utf8") !== generated) throw new Error("vendor_output_drift")
  } else if (process.argv[2] === "--write") writeFileSync(output, generated)
  else throw new Error("Use --check or --write")
}
